"""Sunrise/sunset table for the trip, NOAA solar algorithm, stdlib only.

Run: python -I content/sunset.py  -> rewrites content/sunset.json
Times are Asia/Shanghai (UTC+8, no DST), rounded to the minute, for the
standard -0.833 deg altitude (refraction + solar disc), flat horizon.
Mountains around Chongli make the visible sunset earlier than this.
"""
import json
import math
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

TZ = timezone(timedelta(hours=8))
START = date(2026, 12, 7)
DAYS = 8
PLACES = {
    "beijing": {"name": "Beijing", "lat": 39.9042, "lon": 116.4074},
    "chongli": {"name": "Chongli / Taizicheng", "lat": 40.9, "lon": 115.4},
}


def sun_event_utc_minutes(d, lat, lon, rising):
    """NOAA: minutes after 00:00 UTC on date d. Iterates twice for accuracy."""
    jd0 = d.toordinal() + 1721424.5  # Julian day at 00:00 UTC
    t_min = 720 - 4 * lon  # first guess: solar noon
    for _ in range(3):
        t = (jd0 + t_min / 1440 - 2451545.0) / 36525
        l0 = (280.46646 + t * (36000.76983 + 0.0003032 * t)) % 360
        m = 357.52911 + t * (35999.05029 - 0.0001537 * t)
        e = 0.016708634 - t * (0.000042037 + 0.0000001267 * t)
        mr = math.radians(m)
        c = (math.sin(mr) * (1.914602 - t * (0.004817 + 0.000014 * t))
             + math.sin(2 * mr) * (0.019993 - 0.000101 * t)
             + math.sin(3 * mr) * 0.000289)
        omega = 125.04 - 1934.136 * t
        app_long = l0 + c - 0.00569 - 0.00478 * math.sin(math.radians(omega))
        eps0 = 23 + (26 + (21.448 - t * (46.815 + t * (0.00059 - t * 0.001813))) / 60) / 60
        eps = eps0 + 0.00256 * math.cos(math.radians(omega))
        decl = math.asin(math.sin(math.radians(eps)) * math.sin(math.radians(app_long)))
        y = math.tan(math.radians(eps / 2)) ** 2
        l0r = math.radians(l0)
        eq_time = 4 * math.degrees(
            y * math.sin(2 * l0r) - 2 * e * math.sin(mr)
            + 4 * e * y * math.sin(mr) * math.cos(2 * l0r)
            - 0.5 * y * y * math.sin(4 * l0r) - 1.25 * e * e * math.sin(2 * mr))
        latr = math.radians(lat)
        cos_ha = (math.cos(math.radians(90.833)) / (math.cos(latr) * math.cos(decl))
                  - math.tan(latr) * math.tan(decl))
        ha = math.degrees(math.acos(cos_ha))
        t_min = 720 - 4 * (lon + (ha if rising else -ha)) - eq_time
    return t_min


def local_hhmm(d, minutes_utc):
    moment = datetime(d.year, d.month, d.day, tzinfo=timezone.utc) + timedelta(minutes=minutes_utc)
    moment = (moment + timedelta(seconds=30)).astimezone(TZ)
    return moment.strftime("%H:%M")


def build():
    places = {}
    for pid, p in PLACES.items():
        days = []
        for i in range(DAYS):
            d = START + timedelta(days=i)
            sunrise = local_hhmm(d, sun_event_utc_minutes(d, p["lat"], p["lon"], True))
            sunset = local_hhmm(d, sun_event_utc_minutes(d, p["lat"], p["lon"], False))
            days.append({"date": d.isoformat(), "sunrise": sunrise, "sunset": sunset})
        places[pid] = {"name": p["name"], "lat": p["lat"], "lon": p["lon"], "days": days}
    return {
        "tz": "Asia/Shanghai",
        "method": "NOAA solar algorithm, altitude -0.833 deg, flat horizon; generated by content/sunset.py",
        "places": places,
    }


if __name__ == "__main__":
    out = Path(__file__).with_name("sunset.json")
    out.write_text(json.dumps(build(), indent=2) + "\n", encoding="utf-8")
    print(out.read_text(encoding="utf-8"))
